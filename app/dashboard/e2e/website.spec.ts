import { test, expect } from "@playwright/test";

test("assesses an existing website route set and preserves its evidence after refresh", async ({ page, request }) => {
  const fixture = process.env.SEIRETH_WEBSITE_FIXTURE_URL;
  test.skip(!fixture, "Requires the controlled existing website and browser-fixture network profile");
  await page.goto("/dashboard/");
  const name = "Website browser verification " + Date.now();
  await page.getByLabel("Project name").fill(name);
  await page.getByRole("button", { name: "Create project", exact: true }).click();
  await page.locator(".project-card").filter({ hasText: name }).click();
  await page.getByRole("link", { name: "New assessment" }).click();
  await page.getByRole("button", { name: "Register a new target" }).click();
  await page.getByLabel("Assessment source").selectOption("website");
  await page.getByLabel("Target name").fill("Owned running website");
  await page.getByLabel("Registered URL").fill(fixture!);
  await page.getByLabel("Private staging permission").selectOption("browser-fixture");
  await expect(page.getByLabel("Docker image")).toHaveCount(0);
  await page.getByRole("button", { name: "Register target", exact: true }).click();
  await expect(page.getByText("Website assessment", { exact: true })).toBeVisible();
  await page.getByRole("checkbox", { name: /Use a route plan/ }).check();
  await page.getByLabel("Response URL", { exact: true }).fill(fixture! + "lab/nosniff-first-invalid");
  await page.getByLabel("Route key", { exact: true }).fill("before");
  await page.getByRole("button", { name: "Add route", exact: true }).click();
  await page.getByLabel("Response URL", { exact: true }).nth(1).fill(fixture! + "lab/nosniff-first-valid");
  await page.getByLabel("Route key", { exact: true }).nth(1).fill("after");
  await page.getByRole("checkbox", { name: /HTTP security headers/ }).last().check();
  await page.getByRole("button", { name: "Run assessment", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard\/assessments\//);
  await expect(page.getByText("Release blocked", { exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.locator(".finding")).toHaveCount(1);
  await expect(page.getByRole("heading", { name: "before · completed" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "after · completed" })).toBeVisible();
  await page.reload();
  await expect(page.locator(".finding")).toHaveCount(1);
  await page.locator(".finding summary").click();
  await expect(page.getByRole("region", { name: "Finding evidence" })).toHaveCount(1);
  const id = page.url().split("/").pop();
  const response = await request.get("/api/v1/assessments/" + id + "/report");
  expect(response.status()).toBe(200);
  const report = await response.json();
  expect(report.schema_version).toBe(1);
  expect(report.target.kind).toBe("website");
  expect(report.target.image).toBeNull();
  expect(report.assessment.result.sandbox_backend).toBe("http");
  expect(report.assessment.result.cleanup_verified).toBe(true);
  expect(report.findings[0].route_result_id).toBe(report.assessment.result.routes[0].id);
  expect(report.evidence[0].finding_id).toBe(report.findings[0].id);
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download JSON", exact: true }).click();
  expect((await download).suggestedFilename()).toBe("seireth-assessment-" + id + ".json");
});
